  Future<World?> getWorldById(String id) async => _worlds[id];

  @override
  Future<Chapter?> getChapterById(String chapterId) async {
    for (final world in _worlds.values) {
      for (final chapter in world.chapters) {
        if (chapter.id == chapterId) return chapter;
      }
    }
    return null;
  }

  @override
  Future<Unit?> getUnitById(String unitId) async {
    for (final world in _worlds.values) {
      for (final chapter in world.chapters) {
        for (final unit in chapter.units) {
          if (unit.id == unitId) return unit;
        }
      }
    }
    return null;
  }

  @override
  Future<Lesson?> getLessonById(String lessonId) async {
    for (final world in _worlds.values) {
      for (final chapter in world.chapters) {
        for (final unit in chapter.units) {
          for (final lesson in unit.lessons) {
            if (lesson.id == lessonId) return lesson;
          }
        }
      }
    }
    return null;
  }
